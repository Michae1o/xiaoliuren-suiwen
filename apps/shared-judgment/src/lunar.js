/** 农历年正月初一对应的 UTC 毫秒 */
export function lunarMs(ly, ny) {
  return Date.UTC(ly, +ny.slice(0, 2) - 1, +ny.slice(3));
}

/** 公历 (y,m,d) → 农历 {y,m,d,leap}；超出表范围返回 null */
export function lunarOf(y, m, d) {
  const t0 = Date.UTC(y, m - 1, d);
  let ly = y;
  if (!LUNAR[ly]) return null;
  let base = lunarMs(ly, LUNAR[ly].ny);
  if (t0 < base) {
    ly = y - 1;
    if (!LUNAR[ly]) return null;
    base = lunarMs(ly, LUNAR[ly].ny);
  }
  const off = Math.round((t0 - base) / 86400000);
  if (off < 0) return null;
  const e = LUNAR[ly];
  const order = [];
  for (let i = 1; i <= 12; i++) {
    order.push([i, 0]);
    if (e.leap === i) order.push([i, 1]);
  }
  let acc = 0;
  let k = 0;
  for (; k < order.length; k++) {
    if (off < acc + e.days[k]) break;
    acc += e.days[k];
  }
  if (k >= order.length) return null;
  return { y: ly, m: order[k][0], d: off - acc + 1, leap: order[k][1] };
}

/** 六宫走位：索引 + 步数（1 起）→ 新索引 */
export function advance(gi, steps) {
  return (gi + steps - 1) % 6;
}

